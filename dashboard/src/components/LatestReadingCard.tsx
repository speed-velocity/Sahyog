import type { HealthReading } from '../api/types';
import {
  formatDateTime,
  formatHeartRate,
  formatRelativeTime,
  formatSource,
  formatTimestampTitle,
  isReadingStale,
  isSimulatedSource,
} from '../lib/format';
import { EmptyState } from './EmptyState';
import { Sparkline } from './HeartRateChart';
import { Icon } from './Icon';
import { StatusBadge } from './StatusBadge';

interface LatestReadingCardProps {
  latestReading: HealthReading | null | undefined;
  recentReadings: HealthReading[];
  staleAfterSeconds: number | null | undefined;
  onViewHistory: () => void;
}

export function LatestReadingCard({
  latestReading,
  recentReadings,
  staleAfterSeconds,
  onViewHistory,
}: LatestReadingCardProps) {
  if (!latestReading) {
    return (
      <EmptyState
        description="The backend has not returned a latest heart-rate reading for this monitored person."
        icon="heart"
        title="No readings available"
      />
    );
  }

  const freshnessReported =
    typeof latestReading.is_stale === 'boolean' ||
    (typeof staleAfterSeconds === 'number' && staleAfterSeconds > 0);
  const stale = freshnessReported && isReadingStale(latestReading, staleAfterSeconds);
  const simulated = isSimulatedSource(latestReading.source_kind);
  const history = recentReadings;

  return (
    <div className="latest-reading">
      <div className="latest-reading__main">
        <div>
          <p className="latest-reading__label">Latest heart rate</p>
          <p className="latest-reading__value">
            {formatHeartRate(latestReading.heart_rate_bpm)}
          </p>
          <p className="latest-reading__time">
            <time dateTime={latestReading.observed_at} title={formatTimestampTitle(latestReading.observed_at)}>
              {formatRelativeTime(latestReading.observed_at)}
            </time>
            <span className="muted"> · {formatDateTime(latestReading.observed_at)}</span>
          </p>
        </div>
        {history.length > 1 ? <Sparkline readings={history} staleAfterSeconds={staleAfterSeconds} /> : null}
      </div>

      <div className="latest-reading__badges">
        {simulated ? (
          <StatusBadge
            description="This reading was generated by the SAHYOG simulator."
            label="Simulated reading"
            tone="accent"
          />
        ) : (
          <StatusBadge label={formatSource(latestReading.source_kind)} tone="neutral" />
        )}
        {!freshnessReported ? (
          <StatusBadge label="Freshness not reported" tone="neutral" />
        ) : stale ? (
          <StatusBadge
            description="The reading is older than the backend freshness window."
            label="Stale"
            tone="warning"
          />
        ) : (
          <StatusBadge label="Fresh" tone="success" />
        )}
        {latestReading.activity_context ? (
          <StatusBadge label={latestReading.activity_context} tone="neutral" />
        ) : null}
      </div>

      {stale ? (
        <div className="notice notice--warning notice--compact">
          <span className="notice__icon">
            <Icon name="clock" size={16} />
          </span>
          <p>
            This reading is older than the configured freshness window. It is shown as historical
            data, not as a current measurement.
          </p>
        </div>
      ) : null}

      <div className="latest-reading__footer">
        {simulated ? (
          <p className="muted">Simulated reading — not a live wearable measurement.</p>
        ) : (
          <p className="muted">Source reported by the backend as {formatSource(latestReading.source_kind)}.</p>
        )}
        <button className="btn btn--ghost btn--sm" onClick={onViewHistory} type="button">
          View monitoring details
          <Icon name="chevronRight" size={15} />
        </button>
      </div>
    </div>
  );
}
